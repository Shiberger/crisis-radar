def _negatives(result: dict) -> list[dict]:
    """คอมเมนต์ลบที่ยังไม่ถูกจัดการ — archived = ทีมปิดเคสแล้ว ไม่ควรดันขึ้นมาสั่งงานซ้ำ."""
    return [c for c in (result.get("comments") or [])
            if c.get("sentiment") == "negative" and not c.get("archived")]


def _weight(c: dict) -> float:
    """น้ำหนักของคอมเมนต์ = 1 + reach — สูตรเดียวกับ severity ใน detector.

    ใช้ severity ไม่ใช่จำนวนคอมเมนต์ เพราะคนบ่น 1 คนที่มีคนกดไลก์ตาม 200 คน
    คือประเด็นที่ใหญ่กว่าคนบ่น 3 คนที่ไม่มีใครเห็น — ซึ่งคือสิ่งที่ต้องเอาไปออกประกาศ
    """
    return 1 + int(c.get("reach") or 0)


def _share_weight(c: dict) -> float:
    """น้ำหนักที่ "หารแล้ว" ตามจำนวนเรื่องที่คอมเมนต์นั้นพูดถึง.

    ต้องหาร ไม่งั้นสัดส่วนรวมกันเกิน 100% (วัดจากข้อมูลจริงได้ 126%) เพราะคอมเมนต์ที่ติด
    3 เรื่องถูกนับเต็มทั้ง 3 — แล้วเกณฑ์ "เรื่องเดียวกิน 45% = โฟกัสได้" จะไม่มีความหมายเลย
    เพราะทุกเรื่องเฟ้อขึ้นพร้อมกัน · คนบ่น "เติมเงินแล้วของไม่เข้า" คือครึ่งหนึ่งของความโกรธ
    อยู่ที่เรื่องเงิน อีกครึ่งอยู่ที่ของรางวัล ซึ่งตรงกับความจริงมากกว่านับเต็มทั้งคู่
    """
    n = len(c.get("topics") or []) or 1
    return _weight(c) / n


def _symptoms(comments: list[dict], topic: str) -> list[tuple[str, int]]:
    """คำที่คนพิมพ์ซ้ำ ๆ ในเรื่องนี้ — ตัวที่ทำให้คำขอโทษ "ตรงเรื่อง" แทนที่จะลอย.

    ชื่อหมวดอย่าง 'บั๊ก/เทคนิค' กว้างเกินกว่าจะเอาไปเขียนประกาศ · สิ่งที่เอาไปเขียนได้คือ
    คำที่โผล่ซ้ำในคอมเมนต์จริง เช่น 'เข้าไม่ได้' 8 ครั้ง หรือ 'ติดตั้ง' 5 ครั้ง
    """
    terms = list(TOPIC_KEYWORDS.get(topic, [])) + list(NEGATIVE)
    hits: Counter[str] = Counter()
    for c in comments:
        t = str(c.get("text") or "").lower()
        for term in terms:
            if term in t:
                hits[term] += 1
    # ตัดคำที่โผล่ครั้งเดียว — ยังไม่ใช่ "อาการที่คนเจอร่วมกัน"
    # และตัดคำที่เป็นส่วนของคำอื่นในชุดเดียวกัน (เก็บวลียาวสุดไว้) กันรายงานซ้ำซ้อน
    common = [(w, n) for w, n in hits.most_common() if n >= 2]
    out: list[tuple[str, int]] = []
    for w, n in common:
        if not any(w != o and w in o for o, _ in common):
            out.append((w, n))
    return out[:MAX_SYMPTOMS]


def _quotes(comments: list[dict]) -> list[dict]:
    """คอมเมนต์ที่ควรอ่านก่อนเขียนประกาศ — เรียงตามคนเห็นเยอะสุด."""
    top = sorted(comments, key=lambda c: int(c.get("reach") or 0), reverse=True)[:MAX_QUOTES]
    return [{"text": str(c.get("text") or "").strip(),
             "author": c.get("author", ""),
             "reach": int(c.get("reach") or 0),
             "url": c.get("comment_url", "")} for c in top]


def _topic_block(topic: str, rows: list[dict], total_w: float) -> dict:
    # severity = น้ำหนักเต็ม (ใช้จัดอันดับ ตรงกับ detector) · share = น้ำหนักหาร (รวมได้ 100%)
    w = sum(_weight(c) for c in rows)
    sw = sum(_share_weight(c) for c in rows)
    return {
        "topic": topic,
        "label": TOPIC_LABELS.get(topic, topic or "ทั่วไป"),
        "owner": TOPIC_OWNER.get(topic, "Community"),
        "negative": len(rows),
        "severity": round(w, 1),
        "share": round(sw / total_w * 100, 1) if total_w else 0.0,
        "reach_max": max((int(c.get("reach") or 0) for c in rows), default=0),
        "symptoms": _symptoms(rows, topic),
        "quotes": _quotes(rows),
    }


def build(result: dict) -> dict:
    """สร้างใบสั่งงานจากผลตรวจ 1 รอบ. คืน dict เสมอ — ไม่มีประเด็นก็คืน focus='none'."""
    negs = _negatives(result)
    if len(negs) < MIN_NEGATIVE:
        return {"focus": "none", "negative": len(negs),
                "headline": "ยังไม่มีประเด็นที่ต้องออกประกาศ",
                "why": f"คอมเมนต์ลบ {len(negs)} รายการ — ตอบรายคอมเมนต์พอ ไม่ต้องสื่อสารระดับเพจ",
                "lead": None, "others": [], "apologize": False,
                "say": [], "avoid": [], "next": []}

    # จัดกลุ่มตามเรื่อง · คอมเมนต์ที่ติดหลายเรื่องนับให้ทุกเรื่อง (คนบ่นพร้อมกันได้จริง)
    by_topic: dict[str, list[dict]] = {}
    for c in negs:
        for t in (c.get("topics") or ["_other"]):
            by_topic.setdefault(t, []).append(c)

    total_w = sum(_weight(c) for c in negs)
    blocks = sorted((_topic_block(t, rows, total_w) for t, rows in by_topic.items()),
                    key=lambda b: b["share"], reverse=True)
    named = [b for b in blocks if b["topic"] != "_other"]
    if not named:
        # บ่นแต่จับไม่ได้ว่าเรื่องอะไร — เป็นสัญญาณว่า lexicon ตามภาษาใหม่ไม่ทัน ต้องบอกตรง ๆ
        return {"focus": "unclear", "negative": len(negs),
                "headline": "มีคอมเมนต์ลบ แต่ระบบยังจับไม่ได้ว่าเรื่องอะไร",
                "why": f"คอมเมนต์ลบ {len(negs)} รายการไม่เข้าเงื่อนไขประเด็นไหนเลย "
                       f"— ต้องให้คนอ่านเองก่อนตัดสินใจสื่อสาร",
                "lead": _topic_block("_other", negs, total_w), "others": [],
                "apologize": False,
                "say": ["อ่านคอมเมนต์ที่คนเห็นเยอะสุดเองก่อน — อย่าเพิ่งออกประกาศ"],
                "avoid": ["ออกประกาศจากตัวเลขอย่างเดียวโดยยังไม่รู้ว่าคนบ่นเรื่องอะไร"],
                "next": ["ถ้าเจอคำ/ประเด็นใหม่ที่ระบบไม่รู้จัก แจ้งให้เพิ่มเข้า lexicon รอบหน้า"]}

    lead, second = named[0], (named[1] if len(named) > 1 else None)
    pair = lead["share"] + (second["share"] if second else 0)

    if lead["share"] >= LEAD_SHARE:
        focus = "concentrated"
        headline = f"ขอโทษ/ชี้แจงเรื่อง “{lead['label']}” เรื่องเดียวก่อน"
        why = (f"เรื่องนี้กินความไม่พอใจ {lead['share']:.0f}% "
               f"({lead['negative']} คอมเมนต์) — พูดเรื่องเดียวครอบคลุมคนส่วนใหญ่ได้")
    elif second and pair >= PAIR_SHARE and second["share"] >= SECOND_MIN:
        focus = "multiple"
        headline = f"มี 2 เรื่องพร้อมกัน — “{lead['label']}” และ “{second['label']}” ต้องพูดแยกกัน"
        why = (f"สองเรื่องรวมกัน {pair:.0f}% ของความไม่พอใจ "
               f"({lead['share']:.0f}% + {second['share']:.0f}%) "
               f"— รวบเป็นประกาศเดียวจะกลายเป็นไม่ตอบทั้งคู่")
    else:
        focus = "diffuse"
        headline = "ยังโฟกัสไม่ได้ — อย่าเพิ่งโพสต์ขอโทษ"
        why = (f"ความไม่พอใจกระจายทั่ว {len(named)} เรื่อง เรื่องใหญ่สุดมีแค่ "
               f"{lead['share']:.0f}% — ขอโทษเรื่องเดียวจะไม่ตรงกับคนส่วนใหญ่")

    play = DIFFUSE_PLAY if focus == "diffuse" else PLAYBOOK.get(lead["topic"], DIFFUSE_PLAY)
    others = [b for b in named[1:]][:3]

    out = {
        "focus": focus,
        "negative": len(negs),
        "headline": headline,
        "why": why,
        "lead": lead,
        "others": others,
        "apologize": bool(play.get("apologize")),
        "say": list(play["say"]),
        "avoid": list(play["avoid"]),
        "next": list(play["next"]),
    }
    # 2 เรื่องพร้อมกัน = ทีมต้องรู้ว่าเรื่องที่สองพูดคนละแบบ ไม่ใช่ก๊อปข้อความเดียวไปใช้ทั้งคู่
    if focus == "multiple" and second:
        p2 = PLAYBOOK.get(second["topic"], DIFFUSE_PLAY)
        out["second"] = second
        out["second_say"] = list(p2["say"])[:1]
        out["second_avoid"] = list(p2["avoid"])[:1]
        out["second_apologize"] = bool(p2.get("apologize"))
    return out
